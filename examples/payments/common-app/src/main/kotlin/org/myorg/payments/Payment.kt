package org.myorg.payments

import kotlinx.serialization.Serializable

/** One side of a payment: where the money comes from or goes to. */
@Serializable
data class Party(
    /** `checking` for the source, `card` for the destination, for now. A new kind needs a value, not a field. */
    val kind: String,
    val account: String,
) {
    companion object {
        const val CHECKING = "checking"
        const val CARD = "card"
    }
}

/**
 * The payment as it is. Every payment event carries it, so no consumer ever calls back to ask (event-carried state
 * transfer). Facts about one step, such as why it failed, go on that step's event, never here.
 */
@Serializable
data class Payment(
    /** Generated by the client (`PUT /payments/{id}`), so a retried request is still one payment. */
    val id: String,
    /** From the caller's identity, never from the request body. */
    val customerId: String,
    val from: Party,
    val to: Party,
    /** A decimal string with two decimals, such as `"100.00"`. Never a binary floating-point number. */
    val amount: String,
    /** ISO 4217 code. */
    val currency: String,
    /** When the BFF accepted it, in epoch milliseconds. */
    val submittedAt: Long,
)

/** Why a step or a payment failed. Data, not types: lower kebab case. */
object Reasons {
    const val INSUFFICIENT_FUNDS = "insufficient-funds"
    const val ACCOUNT_CLOSED = "account-closed"

    /** Also an account that isn't the customer's, so accounts can't be probed. */
    const val ACCOUNT_NOT_FOUND = "account-not-found"

    /** Any card failure, refused or declined. */
    const val CARD_DECLINED = "card-declined"

    /** Anything else. */
    const val REJECTED = "rejected"
}

/** The steps of a payment, as `PAYMENT_EXPIRED.step` names them. */
object Steps {
    const val WITHDRAWAL = "withdrawal"
    const val DEPOSIT = "deposit"
    const val REFUND = "refund"

    val ALL = listOf(WITHDRAWAL, DEPOSIT, REFUND)
}
